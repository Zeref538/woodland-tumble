 glyphs={};metrics={}
 for code,gname in [(0,'.notdef'),(32,'space')]+[(c,names[c]) for c in sorted(chars)]:
  pen=TTGlyphPen(None)
  if code==32:glyphs[gname]=pen.glyph();metrics[gname]=(300,0);continue
  c=chars.get(code,'?');shape=unary_union([LineString(p).buffer(weight/2,cap_style=1,join_style=3 if chamfer else 1,quad_segs=5) for p in G[c]])
  left,bottom,right,top=shape.bounds;advance=700 if c.isdigit() else round(right-left+2*bearing);shape=translate(shape,xoff=(advance-(right-left))/2-left)
  polygons=[shape] if shape.geom_type=='Polygon' else list(shape.geoms)
  for polygon in polygons:
   polygon=orient(polygon,sign=-1)
   for ring in [polygon.exterior,*polygon.interiors]:
    pts=list(ring.coords)[:-1];pen.moveTo(tuple(round(v) for v in pts[0]))
    for pt in pts[1:]:pen.lineTo(tuple(round(v) for v in pt))
    pen.closePath()
  glyphs[gname]=pen.glyph();metrics[gname]=(advance,round(shape.bounds[0]))
 fb=FontBuilder(1000,isTTF=True);fb.setupGlyphOrder(order);fb.setupCharacterMap(names);fb.setupGlyf(glyphs);fb.setupHorizontalMetrics(metrics);fb.setupHorizontalHeader(ascent=900,descent=-300,lineGap=0)
